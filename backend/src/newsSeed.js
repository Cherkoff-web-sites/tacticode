export async function ensureNewsSeed() {
  const existing = await query("SELECT COUNT(*)::int AS count FROM news");
  if (Number(existing.rows[0]?.count || 0) > 0) {
    return;
  }

  for (const item of SEED_NEWS) {
    await query(
      `INSERT INTO news (title, description, image_url, display_date, sort_order, is_published)
       VALUES ($1, $2, $3, $4, $5, TRUE)`,
      [item.title, item.description, item.image_url, item.display_date, item.sort_order]
    );
  }

  console.log(`News seed inserted: ${SEED_NEWS.length} items`);
}
